UPDATE pois p
JOIN tmp_shahe_visible_coords c ON c.name = p.name
SET
  p.map_x = c.map_x,
  p.map_y = c.map_y,
  p.longitude = ROUND(116.286500 + (c.map_x - 1024) * 0.00000265, 6),
  p.latitude = ROUND(40.158800 - (c.map_y - 990) * 0.00000220, 6)
WHERE p.place_group_id = 4;

DELETE e
FROM route_edges e
JOIN pois fp ON fp.id = e.from_poi_id
JOIN pois tp ON tp.id = e.to_poi_id
WHERE fp.place_group_id = 4
  AND tp.place_group_id = 4;

DELETE FROM pois
WHERE place_group_id = 4
  AND area_code = 'route';

